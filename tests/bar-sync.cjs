const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { JSDOM } = require(path.join(process.env.TEMP, 'warmup-validation/node_modules/jsdom'));
(async () => {
  const dom = new JSDOM(fs.readFileSync('index.html', 'utf8'), { url: 'http://localhost/', runScripts: 'outside-only', pretendToBeVisual: true });
  const w = dom.window;
  const add = w.document.addEventListener.bind(w.document);
  w.document.addEventListener = (event, ...args) => { if (event !== 'DOMContentLoaded') add(event, ...args); };
  w.DRINK_RELAY_STORE_CONFIG = { instanceId: 'sync-test' };
  let source = fs.readFileSync('app.js', 'utf8');
  const end = source.lastIndexOf('})();');
  source = source.slice(0, end) + 'window.syncTest={state,refreshSharedOrders,loadOrders};' + source.slice(end);
  w.eval(source);
  const t = w.syncTest;
  let reads = 0, clockCalls = 0, release;
  const stalled = new Promise(resolve => { release = resolve; });
  w.DrinkRelayClock = { now: () => Date.now(), sync: () => { clockCalls++; return new Promise(() => {}); } };
  const order = { id: 'missed-order', created_at: new Date().toISOString(), status: 'ordered', quantity: 1, drink_name: 'test', events: [] };
  t.state.syncMode = 'supabase';
  t.state.view = 'reception';
  t.state.booted = true;
  t.state.soundEnabled = false;
  t.state.supabase = { from() { return { select() { return this; }, in() { return this; }, gte() { return this; }, order() { reads++; return stalled.then(() => ({ data: reads ? [order] : [], error: null })); } }; } };
  const first = t.refreshSharedOrders();
  await t.refreshSharedOrders();
  assert.equal(reads, 2, 'overlapping refresh must not issue duplicate queries');
  release();
  await first;
  assert.equal(t.state.orders.length, 1, 'missed realtime order recovered despite stalled clock');
  assert.ok(t.state.knownIds.has('missed-order'));
  await t.refreshSharedOrders();
  assert.equal(clockCalls, 1, '5-second recovery must not repeatedly synchronize clock');
  let result = { data: [order], error: null };
  const filters = [];
  t.state.supabase = { from() { return { select() { return this; }, in(field, values) { filters.push([...values]); return this; }, gte() { return this; }, order() { return Promise.resolve(result); } }; } };
  const history = { ...order, id: 'history', status: 'served', updated_at: new Date().toISOString() };
  t.state.orders.push(history);
  await t.loadOrders({ openOnly: true });
  assert.equal(filters.length, 1, 'bar recovery issues only one query');
  assert.deepEqual(filters[0], ['ordered', 'making', 'made']);
  assert.ok(t.state.orders.some(item => item.id === 'history'), 'existing history retained');
  assert.equal(await t.loadOrders({ openOnly: true }), false, 'unchanged results skip redraw');
  result = { data: [], error: null };
  await t.loadOrders({ openOnly: true });
  assert.ok(!t.state.orders.some(item => item.id === order.id), 'orders completed elsewhere disappear from open list');
  let finish;
  t.state.supabase.from = () => ({ select() { return this; }, in() { return this; }, order() { return new Promise(resolve => { finish = resolve; }); } });
  const stale = t.loadOrders({ openOnly: true });
  t.state.orders.push({ ...order, id: 'new-realtime-order' });
  finish({ data: [], error: null });
  assert.equal(await stale, false);
  assert.ok(t.state.orders.some(item => item.id === 'new-realtime-order'), 'stale response cannot erase concurrent realtime updates');
  console.log('PASS missed order recovery, stalled clock, refresh deduplication and clock throttling');
  console.log('PASS open-only query, history retention, unchanged redraw suppression, completed order removal and stale response protection');
  dom.window.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
