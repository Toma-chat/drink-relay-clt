// Publish the same STD profile used by regular unlimited plans, without copying products.
const fs=require('node:fs'),vm=require('node:vm');
const context={window:{}};
for(const file of ['store-config.js','unlimited-config.js'])vm.runInNewContext(fs.readFileSync(file,'utf8'),context);
const store=context.window.DRINK_RELAY_STORE_CONFIG.instanceId.trim().toLowerCase().replace(/[^a-z0-9_-]+/g,'-');
const profile=context.window.DRINK_RELAY_UNLIMITED_CONFIG.planRules['unlimited-alcohol-all-day'];
const quote=s=>"'"+s.replaceAll("'","''")+"'";
fs.writeFileSync('supabase/warmup-menu-update.sql',`-- Generated by scripts/build-warmup-profile.cjs from unlimited-config.js.
-- Only the shared Warmup profile changes; QR, sessions, daily code, prices and orders are preserved.
begin;
do $publish$
declare previous jsonb; desired jsonb := ${quote(JSON.stringify(profile))}::jsonb; missing text;
begin
  select profile into previous from warmup_private.stores where id=${quote(store)} for update;
  if not found then raise exception 'Warmup store missing'; end if;
  select string_agg(id,',') into missing from jsonb_array_elements_text(desired->'includeItemIds') x(id)
    where not exists(select 1 from public.drink_app_settings s,jsonb_array_elements(s.menu::jsonb) c,jsonb_array_elements(c->'items') i where s.id='main' and i->>'id'=x.id);
  if missing is not null then raise exception 'STD products missing from shared menu: %',missing; end if;
  if previous is distinct from desired then
    update warmup_private.stores set profile=desired where id=${quote(store)};
    insert into warmup_private.audit(store,action,detail) values(${quote(store)},'profile-published',jsonb_build_object('source','unlimited-config.js','previous',previous,'profile',desired));
  end if;
end $publish$;
commit;
`);
console.log('Generated shared Warmup STD profile:',profile.includeItemIds.length,'products.');
